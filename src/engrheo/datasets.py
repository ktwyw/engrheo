def available() -> list[str]:
    """Names of the bundled data files."""
    return sorted(INFO)


def path(name: str) -> str:
    """Filesystem path of a bundled data file (works when engrheo is installed, including on Colab)."""
    if name not in INFO:
        raise KeyError(f"Unknown data file {name!r}. Available: {', '.join(available())}")
    return str(resources.files("engrheo.data").joinpath(name))


def info(name: str) -> str:
    """Source, content, units and licence of a data file."""
    if name not in INFO:
        raise KeyError(f"Unknown data file {name!r}.")
    return INFO[name]
